const { chromium } = require('/tmp/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    page.setDefaultTimeout(20000);
    const errors = [];
    const requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (/\/(sinir|ic-organlar)\.glb/.test(request.url())) requests.push(request.url()); });
    const click = selector => page.locator(selector).first().evaluate(el => el.click());
    await page.goto('http://127.0.0.1:4173/?mode=explore&scope=all', { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => !document.getElementById('atlas-bones-toggle').disabled, null, { timeout: 150000 });
    assert.deepEqual(requests, [], 'Optional systems loaded at startup');
    await click('#atlas-bones-toggle');
    assert.equal(await page.locator('#atlas-context-layers').isVisible(), true);
    await click('[data-context-layer="nervous"]');
    await page.waitForFunction(() => document.getElementById('viewer').dataset.referenceLayers.includes('nervous'), null, { timeout: 90000 });
    await page.fill('#structure-search', 'подмышечный нерв');
    await click('.search-result');
    assert.equal(await page.locator('#viewer').getAttribute('data-selected-reference-layer'), 'nervous');
    assert.match(await page.locator('#mobile-muscle-name').textContent(), /Подмышечный нерв/);
    await click('#mobile-bone-reference summary');
    assert.match(await page.locator('#mobile-bone-reference').textContent(), /Дельтовидная мышца/);
    const card = await page.locator('#mobile-muscle-card').boundingBox();
    const viewer = await page.locator('.viewer-wrap').boundingBox();
    assert.ok(card.y >= viewer.y + viewer.height - 1, 'Context card overlaps the 3D workspace');
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: '/tmp/muscle-memory-comfort-nerves.png', fullPage: true, scale: 'css', animations: 'disabled' });
    await page.locator('#mobile-bone-reference .nerve-muscle-links button').filter({ hasText: 'Дельтовидная' }).first().evaluate(el => el.click());
    assert.equal(await page.locator('#viewer').getAttribute('data-atlas-view'), 'muscles');
    assert.match(await page.locator('#mobile-muscle-name').textContent(), /Дельтовидная/);
    assert.ok(await page.locator('#structure-reference-facts').isVisible());
    console.log('[smoke:comfort] lazy nerve layer, mobile selection and nerve → muscle card OK');

    await click('#atlas-bones-toggle');
    await click('[data-context-layer="organs"]');
    await page.waitForFunction(() => document.getElementById('viewer').dataset.referenceLayers.includes('organs'), null, { timeout: 90000 });
    await click('#atlas-context-muscles');
    assert.equal(await page.locator('#atlas-context-muscles').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#viewer').getAttribute('data-muscle-mode'), 'ghost');
    await click('#atlas-context-muscles');
    await page.fill('#structure-search', 'почка');
    await click('.search-result');
    assert.equal(await page.locator('#viewer').getAttribute('data-selected-reference-layer'), 'organs');
    assert.match(await page.locator('#mobile-muscle-name').textContent(), /Почка/);
    await click('#focus-selected');
    await page.setViewportSize({ width: 1440, height: 960 });
    await page.evaluate(() => scrollTo(0, 0));
    assert.equal(await page.locator('#atlas-context-layers').isVisible(), true);
    assert.equal(await page.locator('#mobile-page-scroll').isHidden(), true);
    await page.screenshot({ path: '/tmp/muscle-memory-comfort-organs.png', scale: 'css', animations: 'disabled' });
    await click('[data-context-layer="organs"]');
    assert.ok(!(await page.locator('#viewer').getAttribute('data-reference-layers')).includes('organs'));
    assert.equal(await page.locator('#viewer').getAttribute('data-selected-reference-layer'), '');
    await click('[data-context-layer="organs"]');
    await page.waitForFunction(() => document.getElementById('viewer').dataset.referenceLayers.includes('organs'));
    assert.equal(requests.filter(url => url.includes('ic-organlar')).length, 1, 'A cached layer was fetched again');
    assert.equal(requests.filter(url => url.includes('sinir')).length, 1);
    assert.deepEqual(errors, []);
    console.log('[smoke:comfort] organ layer, ghost muscles, desktop layout, deselection and cache OK');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
