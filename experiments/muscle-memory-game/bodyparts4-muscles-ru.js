function normalizedMuscleKey(sourceName) {
  return String(sourceName || "")
    .trim()
    .toLocaleLowerCase("en-US")
    .replace(/\b(right|left)\b/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

export function bodyPartsMuscleNameRu(sourceName) {
  const source = String(sourceName || "").trim();
  if (!source) return null;

  const lower = source.toLocaleLowerCase("en-US");
  const exact = EXACT_RU.get(lower);
  if (exact) return exact;

  const key = normalizedMuscleKey(source);
  const base = BASE_RU.get(key);
  if (!base) return null;

  const hasRight = /\bright\b/i.test(source);
  const hasLeft = /\bleft\b/i.test(source);
  const side = hasRight && !hasLeft ? " (справа)" : hasLeft && !hasRight ? " (слева)" : "";
  return base + side;
}

export function bodyPartsMuscleTranslationCoverage(sourceNames) {
  const missing = [];
  for (const source of sourceNames || []) {
    if (!bodyPartsMuscleNameRu(source)) missing.push(source);
  }
  return { total: (sourceNames || []).length, missing };
}
