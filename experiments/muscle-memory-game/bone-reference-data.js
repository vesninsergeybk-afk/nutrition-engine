export function boneCardForTerm(term) {
  const card = BONE_CATALOG[term.canonicalKey];
  if (!card) return null;
  let key = "skull";
  if (card.regionRu.includes("Позвоночник") || card.regionRu.includes("позвоночник")) key = "spine";
  if (card.regionRu === "Грудная клетка") key = "thorax";
  if (["Кисть", "Плечевой пояс", "Плечо", "Предплечье"].includes(card.regionRu)) key = "upper";
  if (["Стопа", "Голень", "Колено", "Бедро", "Таз"].includes(card.regionRu)) key = "lower";
  if (card.regionRu === "Гортань") key = "larynx";
  if (card.kindRu === "Зуб") key = "teeth";
  let descriptionRu = card.descriptionRu;
  if (term.ribNumber) {
    descriptionRu += term.ribNumber <= 7 ? " Это истинное ребро: его хрящ соединяется непосредственно с грудиной." : term.ribNumber <= 10 ? " Его хрящ присоединяется к вышележащему хрящу в составе рёберной дуги." : " Это колеблющееся ребро: передний конец не соединён с грудиной.";
  }
  return { ...card, nameRu: term.nameRu, descriptionRu, source: BONE_REFERENCE_SOURCES[key] };
}
