export function bodyPartsAnatomyKind(part) {
  if (!part) return null;
  if (part.system === "muscular" || SKELETAL_TAGGED_MUSCLE_IDS.has(part.conceptId)) {
    return "muscle";
  }
  if (BONE_CONCEPT_IDS.has(part.conceptId)) return "bone";
  return null;
}

export function bodyPartsClassificationStats(parts) {
  let muscles = 0;
  let bones = 0;
  let excludedSkeletal = 0;
  for (const part of parts || []) {
    const kind = bodyPartsAnatomyKind(part);
    if (kind === "muscle") muscles += 1;
    else if (kind === "bone") bones += 1;
    else if (part.system === "skeletal") excludedSkeletal += 1;
  }
  return { muscles, bones, excludedSkeletal };
}
