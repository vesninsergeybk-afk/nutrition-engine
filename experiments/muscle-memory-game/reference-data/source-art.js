export function referenceSourceArtForStructure(structureId) {
  return REFERENCE_SOURCE_ART.filter(
    (item) =>
      item.structureId === structureId &&
      (item.artScope === "exact-card" || item.artScope === "exact-card-part")
  );
}

export function referenceSupplementArtForStructure(structureId) {
  return REFERENCE_SOURCE_ART.filter(
    (item) =>
      item.artScope === "group-supplement" &&
      item.structureIds?.includes(structureId)
  );
}

export function publishableReferenceSourceArtForStructure(structureId) {
  return referenceSourceArtForStructure(structureId).filter(
    (item) =>
      item.status === "asset-ready" &&
      Boolean(item.assetPath) &&
      ["public-domain", "cc0", "cc-by", "cc-by-sa", "licensed", "owned"].includes(
        item.rightsStatus
      )
  );
}
